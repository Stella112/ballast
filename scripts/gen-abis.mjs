// Generates lib/abis.ts from Foundry artifacts (Ballast) and explorer-verified Mezo ABIs.
// Mezo ABIs come from abi/mezo/<C>.json (fetched from the testnet explorer; see docs/VERIFICATION.md),
// filtered to the functions the app uses. Re-run after `forge build`.
import fs from "node:fs";
const ballast = ["BallastFactory", "BallastAccount", "BallastAccountNFT", "BallastRouter", "BallastRepaymentAdapter", "BallastHedge", "BallastHedgeFactory", "BallastBridgeReceiver"];
const artifactFile = { BallastHedgeFactory: "BallastHedge.sol" };
const mezo = {
  TroveManager: ["getTroveStatus","getTroveDebt","getTroveColl","getTrovePrincipal","getTroveInterestOwed","getNominalICR","getCurrentICR","getEntireDebtAndColl","getTCR","checkRecoveryMode","Troves","getTroveOwnersCount","getTroveFromTroveOwnersArray","MCR"],
  SortedTroves: ["getFirst","getLast","getNext","getPrev","getSize","contains","findInsertPosition"],
  HintHelpers: ["getApproxHint","computeNominalCR"],
  PriceFeed: ["fetchPrice"],
  BorrowerOperations: ["minNetDebt","MUSD_GAS_COMPENSATION","getBorrowingFee","borrowingRate"],
};
let out = "// AUTO-GENERATED by scripts/gen-abis.mjs — do not edit.\n";
for (const c of ballast) {
  const abi = JSON.parse(fs.readFileSync(`out/${artifactFile[c] ?? c + ".sol"}/${c}.json`, "utf8")).abi;
  out += `export const ${c}Abi = ${JSON.stringify(abi)} as const;\n`;
}
for (const [c, fns] of Object.entries(mezo)) {
  const p = `abi/mezo/${c}.json`;
  const abi = JSON.parse(fs.readFileSync(p, "utf8")).filter((e) => e.type === "function" && fns.includes(e.name));
  const missing = fns.filter((f) => !abi.some((e) => e.name === f));
  if (missing.length) throw new Error(`${c}: missing in verified ABI: ${missing}`);
  out += `export const ${c}Abi = ${JSON.stringify(abi)} as const;\n`;
}
const musd = JSON.parse(fs.readFileSync("abi/mezo/MUSD.json", "utf8")).filter((e) => e.type === "function" && ["balanceOf","allowance","approve","decimals","symbol","transfer"].includes(e.name));
out += `export const MUSDAbi = ${JSON.stringify(musd)} as const;\n`;
const morpho = JSON.parse(fs.readFileSync(".upstream/morpho-blue/out/Morpho.sol/Morpho.json", "utf8")).abi.filter((e) => e.type === "function" && ["market","position","supply","withdraw","accrueInterest"].includes(e.name));
out += `export const MorphoAbi = ${JSON.stringify(morpho)} as const;
`;
for (const [c, fns] of Object.entries({ PoolsRouter: ["getAmountsOut"], WormholeTokenBridge: ["transferTokensWithPayload", "wrappedAsset", "isTransferCompleted"] })) {
  const abi = JSON.parse(fs.readFileSync(`abi/ext/${c}.json`, "utf8")).filter((e) => e.type === "function" && fns.includes(e.name));
  const missing = fns.filter((f) => !abi.some((e) => e.name === f));
  if (missing.length) throw new Error(`${c}: missing in verified ABI: ${missing}`);
  out += `export const ${c}Abi = ${JSON.stringify(abi)} as const;
`;
}
out += `export const WormholeCoreAbi = [{"anonymous":false,"inputs":[{"indexed":true,"name":"sender","type":"address"},{"indexed":false,"name":"sequence","type":"uint64"},{"indexed":false,"name":"nonce","type":"uint32"},{"indexed":false,"name":"payload","type":"bytes"},{"indexed":false,"name":"consistencyLevel","type":"uint8"}],"name":"LogMessagePublished","type":"event"},{"inputs":[],"name":"messageFee","outputs":[{"name":"","type":"uint256"}],"stateMutability":"view","type":"function"}] as const;
`;
fs.writeFileSync("lib/abis.ts", out);
console.log("wrote lib/abis.ts");
